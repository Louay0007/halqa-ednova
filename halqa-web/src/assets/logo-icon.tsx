export default function LogoIcon({ className }: { className?: string }) {
  // Two marks can share a page (shell header + /enter). SVG gradient ids are
  // document-global, so a duplicated id resolves to the wrong (often hidden)
  // element and the second mark paints blank. useId keeps each instance unique.
  const uid = useId().replace(/:/g, '');
  return (
    <svg
      className={className}
      viewBox="296 282 1346 1346"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      aria-hidden="true"
      focusable="false"
    >
      <defs>
        {Object.entries(GRADIENTS).map(([id, g]) => (
          <linearGradient
            key={id}
            id={`halqa-${uid}-${id}`}
            gradientUnits="userSpaceOnUse"
            x1={g.x1}
            y1={g.y1}
            x2={g.x2}
            y2={g.y2}
          >
            {g.stops.map(([offset, color]) => (
              <stop key={offset} offset={offset} stopColor={color} />
            ))}
          </linearGradient>
        ))}
      </defs>
      {PATHS.map((p, i) => (
        <path key={i} d={p.d} fill={`url(#halqa-${uid}-${p.fill})`} fillRule="evenodd" />
      ))}
    </svg>
  );
}
